import assert from 'node:assert/strict'
import { after, test } from 'node:test'

import { Window } from 'happy-dom'

const domWindow = new Window({ url: 'https://api.example.com/' })
const domGlobals = [
  'window',
  'document',
  'navigator',
  'HTMLElement',
  'Node',
  'Element',
  'Event',
  'CustomEvent',
  'MutationObserver',
  'requestAnimationFrame',
  'cancelAnimationFrame',
  'getComputedStyle',
] as const

for (const key of domGlobals) {
  Object.defineProperty(globalThis, key, {
    configurable: true,
    value: domWindow[key],
  })
}

const { act } = await import('react')
const { createRoot } = await import('react-dom/client')
const { HeroTerminalDemo } = await import('../hero-terminal-demo')

const reactTestGlobals = globalThis as typeof globalThis & {
  IS_REACT_ACT_ENVIRONMENT?: boolean
}
reactTestGlobals.IS_REACT_ACT_ENVIRONMENT = true

after(() => {
  domWindow.close()
})

test('shows a ready-to-copy Grok request as the default homepage demo', async () => {
  const container = document.createElement('div')
  document.body.append(container)
  const root = createRoot(container)

  await act(async () => {
    root.render(<HeroTerminalDemo />)
  })

  const providerTabs = [...container.querySelectorAll('button')]
  assert.equal(providerTabs[0]?.textContent, 'Grok')
  assert.match(
    container.textContent ?? '',
    /https:\/\/api\.example\.com\/v1\/chat\/completions/
  )
  assert.match(container.textContent ?? '', /grok-4\.5/)
  assert.match(container.textContent ?? '', /Content-Type: application\/json/)

  await act(async () => root.unmount())
  container.remove()
})
